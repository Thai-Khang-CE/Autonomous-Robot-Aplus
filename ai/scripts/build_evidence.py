"""Assemble results/evidence/ from real artifacts and write EVIDENCE_MANIFEST.md.

Every file in the evidence tree is either (a) a copy of a raw artifact produced by an executed
command, (b) a figure generated by a script directly from raw data, or (c) a PNG rendered from a
captured log file (marked "NOT a desktop screenshot" inside the image). The manifest lists the
type, source data and producing command for each item.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd

from robot_aplus_rl.config import PROJECT_ROOT

R = PROJECT_ROOT / "results"
E = R / "evidence"
FIG = R / "figures"
PY = sys.executable
rows: list[dict] = []


def rel(p: Path) -> str:
    return p.resolve().relative_to(PROJECT_ROOT).as_posix()


def add(dst: Path, kind: str, source: str, command: str, config: str = "", seed: str = "") -> None:
    rows.append({"artifact": rel(dst), "type": kind, "source": source, "command": command,
                 "config": config, "seed": seed})


def copy(src: Path, dst_dir: Path, kind: str, command: str, name: str | None = None, **kw) -> None:
    if not src.exists():
        print("missing, skipped:", src)
        return
    dst_dir.mkdir(parents=True, exist_ok=True)
    dst = dst_dir / (name or src.name)
    shutil.copy2(src, dst)
    add(dst, kind, rel(src), command, **kw)


def render(src: Path, dst: Path, title: str, extra: list[str] | None = None, **kw) -> None:
    if not src.exists():
        print("missing, skipped:", src)
        return
    subprocess.run([PY, str(PROJECT_ROOT / "scripts" / "render_log_image.py"), str(src), str(dst),
                    "--title", title] + (extra or []), check=True, cwd=PROJECT_ROOT)
    add(dst, "rendered log (not a desktop screenshot)", rel(src), "scripts/render_log_image.py", **kw)


def fig(name: str, dst_dir: Path, new_name: str, producer: str, source: str) -> None:
    for ext in ("png", "pdf"):
        src = FIG / f"{name}.{ext}"
        if src.exists():
            dst_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst_dir / f"{new_name}.{ext}")
            add(dst_dir / f"{new_name}.{ext}", "generated figure (from data)", source, producer)


def training_excerpt(run: Path, out: Path) -> None:
    """Plain-text excerpt of the real SB3 progress.csv (selected columns, every k-th row)."""
    df = pd.read_csv(run / "logs" / "progress.csv")
    cols = [c for c in ("time/total_timesteps", "time/time_elapsed", "rollout/ep_rew_mean",
                        "rollout/ep_len_mean", "rollout/success_rate", "train/loss",
                        "train/value_loss", "train/policy_gradient_loss", "train/actor_loss",
                        "train/critic_loss", "train/ent_coef", "train/n_updates") if c in df]
    d = df[cols].dropna(subset=["time/total_timesteps"])
    step = max(1, len(d) // 25)
    sel = pd.concat([d.iloc[::step], d.tail(1)]).drop_duplicates()
    sel.columns = [c.split("/")[-1] for c in sel.columns]
    out.write_text(f"# excerpt of {rel(run / 'logs' / 'progress.csv')} ({len(d)} rows; every "
                   f"{step}th row + last row)\n" + sel.to_string(index=False, float_format=lambda x: f"{x:.4g}")
                   + "\n", encoding="utf-8")


def run_info_text(run: Path, out: Path) -> None:
    d = json.loads((run / "run_info.json").read_text(encoding="utf-8"))
    keys = ["run_name", "algorithm", "label", "status", "command", "seed", "requested_timesteps",
            "executed_timesteps", "n_gradient_updates", "policy_param_l2_change",
            "policy_param_changed", "reload_check", "best_model_exists", "wall_time_s",
            "started_utc", "finished_utc", "versions"]
    out.write_text(json.dumps({k: d.get(k) for k in keys}, indent=2), encoding="utf-8")


def training_stage(algo: str, folder: str) -> None:
    dst = E / folder
    for run in sorted((R / algo).glob("*_seed*")):
        info = run / "run_info.json"
        if not info.exists():
            continue
        d = json.loads(info.read_text(encoding="utf-8"))
        sub = dst / "runs" / run.name
        cmd = d["command"]
        cfg = d["algo_config_file"]
        seed = str(d["seed"])
        for f in ("run_info.json", "stdout.log", "training_episodes.csv", "evaluations.npz",
                  "final_model.zip", "best_model.zip"):
            copy(run / f, sub, "raw artifact", cmd, config=cfg, seed=seed)
        copy(run / "logs" / "progress.csv", sub, "raw artifact (SB3 logger)", cmd, config=cfg,
             seed=seed)
        for ck in sorted((run / "checkpoints").glob("*.zip")):
            copy(ck, sub / "checkpoints", "raw artifact (periodic checkpoint)", cmd, config=cfg, seed=seed)
        mon = run / "monitor"
        if mon.exists():
            for m in sorted(mon.glob("*.csv")):
                copy(m, sub / "monitor", "raw artifact (SB3 Monitor)", cmd, config=cfg, seed=seed)
        if d["status"] == "completed" and d["label"] != "smoke":
            training_excerpt(run, sub / "progress_excerpt.txt")
            add(sub / "progress_excerpt.txt", "text excerpt of raw log", rel(run / "logs/progress.csv"),
                "scripts/build_evidence.py", config=cfg, seed=seed)
            render(sub / "progress_excerpt.txt", dst / f"{algo}_{run.name}_training_log.png",
                   f"{algo.upper()} {run.name}: SB3 training log (logs/progress.csv)", config=cfg,
                   seed=seed)
        if d["status"] == "completed":
            run_info_text(run, sub / "run_summary.json")
            add(sub / "run_summary.json", "subset of raw run_info.json", rel(info),
                "scripts/build_evidence.py", config=cfg, seed=seed)
            render(sub / "run_summary.json", dst / f"{algo}_{run.name}_checkpoint_reload.png",
                   f"{algo.upper()} {run.name}: executed steps, updates, checkpoint reload check",
                   config=cfg, seed=seed)


def main() -> None:
    E.mkdir(parents=True, exist_ok=True)
    # 01 environment
    d1 = E / "01_environment"
    copy(R / "environment_report.json", d1, "raw artifact", "scripts/check_environment.py")
    if (d1 / "check_environment_output.txt").exists():
        add(d1 / "check_environment_output.txt", "captured terminal output",
            "stdout of scripts/check_environment.py", "scripts/check_environment.py")
        add(d1 / "check_environment_terminal.png", "rendered log (not a desktop screenshot)",
            rel(d1 / "check_environment_output.txt"), "scripts/render_log_image.py")
    for f in ("requirements.txt", "requirements-lock.txt", "pyproject.toml"):
        copy(PROJECT_ROOT / f, d1, "dependency record", "uv pip freeze / manual pin")
    for f in sorted((PROJECT_ROOT / "configs").glob("*.yaml")):
        copy(f, d1 / "configs", "configuration", "-")
    fig("environment_overview", d1, "gymnasium_environment", "scripts/plot_environment.py",
        "simulator (generate_scenario, cast_rays, reference_path)")
    fig("observation_example", d1, "observation_example", "scripts/plot_environment.py",
        "env.reset() observation")
    copy(FIG / "environment_overview_observations.json", d1, "raw artifact",
         "scripts/plot_environment.py")
    # 02 tests
    d2 = E / "02_tests"
    copy(R / "test_report.txt", d2, "captured terminal output",
         ".venv/Scripts/python.exe -m pytest -v -o addopts= -p no:cacheprovider")
    if (d2 / "pytest_results.png").exists():
        add(d2 / "pytest_results.png", "rendered log (not a desktop screenshot)",
            "results/test_report.txt", "scripts/render_log_image.py")
    # 03/04 training
    training_stage("ppo", "03_ppo_training")
    training_stage("sac", "04_sac_training")
    for algo, folder in (("ppo", "03_ppo_training"), ("sac", "04_sac_training")):
        for lab in ("controlled", "extended"):
            fig(f"{algo}_reward_curve_{lab}", E / folder, f"{algo}_reward_curve_{lab}",
                "scripts/plot_results.py", f"results/{algo}/{lab}_seed*/training_episodes.csv")
    fig("training_comparison_extended", E / "05_evaluation", "algorithm_training_comparison",
        "scripts/plot_results.py", "training_episodes.csv")
    fig("validation_success_extended", E / "05_evaluation", "validation_success_curves",
        "scripts/plot_results.py", "evaluations.npz")
    # 05 evaluation
    d5 = E / "05_evaluation"
    for f in sorted((R / "evaluation" / "episodes").glob("*.csv")):
        copy(f, d5 / "episodes", "raw evaluation episodes", "scripts/evaluate.py (see RUN_MANIFEST.md)")
    for f in sorted((R / "evaluation" / "robustness" / "episodes").glob("*.csv")):
        copy(f, d5 / "robustness_r025", "raw evaluation episodes (robot radius 0.25 m)",
             "scripts/evaluate.py --robot-radius 0.25")
    for f in ("summary.md", "summary_by_label.csv", "summary_by_group.csv", "report_numbers.json",
              "test_set_50_per_category.json"):
        copy(R / "evaluation" / f, d5, "derived from raw episodes", "scripts/summarize.py / make_report_assets.py")
    for f in sorted((R / "evaluation" / "logs").glob("*.log")):
        copy(f, d5 / "logs", "captured terminal output", "scripts/run_experiments.py --stages evaluate")
    fig("eval_success_rate", d5, "algorithm_comparison_success", "scripts/plot_results.py",
        "results/evaluation/summary_by_label.csv")
    fig("eval_collision_rate", d5, "algorithm_comparison_collision", "scripts/plot_results.py",
        "results/evaluation/summary_by_label.csv")
    summ = R / "evaluation" / "summary.md"
    if summ.exists():
        render(summ, d5 / "evaluation_summary_table.png", "Evaluation summary (results/evaluation/summary.md)",
               ["--grep", r"^\|", "--max-width", "175"])
    # 06 trajectories
    d6 = E / "06_trajectories"
    for name, new in (("trajectories_grid", "trajectories_same_scenarios"),
                      ("ppo_examples", "ppo_trajectory_success_and_failure"),
                      ("sac_examples", "sac_trajectory_success_and_failure"),
                      ("random_examples", "random_trajectory_examples")):
        fig(name, d6, new, "scripts/plot_results.py", "results/evaluation/trajectories/*.json")
    for f in sorted((R / "evaluation" / "trajectories").glob("*.json")):
        copy(f, d6 / "trajectory_data", "raw trajectories", "scripts/evaluate.py")
    # 07 report
    d7 = E / "07_report"
    rep = PROJECT_ROOT / "reports" / "week09_team"
    for f in ("weekly_report.pdf", "weekly_report.tex", "viet_section.tex", "compile_log.txt"):
        copy(rep / f, d7, "report", "pdflatex (TeX Live Docker image)")
    for f in sorted((rep / "tables").glob("*.tex")):
        copy(f, d7 / "tables", "generated table (from raw data)", "scripts/make_report_assets.py")
    for f in sorted(d7.glob("page_*.png")):
        add(f, "rendered PDF page", "reports/week09/weekly_report.pdf", "pdftoppm")
    copy(PROJECT_ROOT / "RUN_MANIFEST.md", E, "run manifest", "scripts/build_manifest.py")

    df = pd.DataFrame(rows).drop_duplicates("artifact")
    md = ["# EVIDENCE_MANIFEST - Robot Aplus Week 9 (Nguyen Van Viet)", "",
          "All evidence comes from runs executed locally on 2026-11-13 in the simplified 2D Gymnasium",
          "simulator (NOT Gazebo, NOT a physical robot). No desktop screenshots were taken: images of",
          "terminal output are RENDERED from the captured log file named in the `source` column and",
          "carry the banner 'NOT a desktop screenshot'. Plots are generated directly from raw data.", "",
          "Types: raw artifact = file written by the executed program; captured terminal output = stdout",
          "redirected to a file; rendered log = PNG drawn from such a file; generated figure = plot",
          "computed from raw data by the named script.", "",
          df.to_markdown(index=False), ""]
    (E / "EVIDENCE_MANIFEST.md").write_text("\n".join(md), encoding="utf-8")
    print(f"evidence manifest: {len(df)} artifacts")


if __name__ == "__main__":
    main()
