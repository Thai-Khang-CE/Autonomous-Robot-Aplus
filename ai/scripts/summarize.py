"""Aggregate every evaluation episode CSV into summary tables (CSV, Markdown, LaTeX).

Outputs in results/evaluation/:
    summary_by_label.csv        one row per evaluated policy/checkpoint (overall + per category)
    summary_by_group.csv        multi-seed groups: per-seed success-rate mean / std / min / max
    summary.md                  human-readable tables
and reports/week09/tables/*.tex for the report.
"""

from __future__ import annotations

import re

import pandas as pd

from robot_aplus_rl.config import PROJECT_ROOT
from robot_aplus_rl.evaluation import summarise

EVAL = PROJECT_ROOT / "results" / "evaluation"
TABLES = PROJECT_ROOT / "reports" / "week09" / "tables"


def group_of(label: str) -> str:
    return re.sub(r"_seed\d+", "", label)


def load_all() -> pd.DataFrame:
    frames = [pd.read_csv(p) for p in sorted((EVAL / "episodes").glob("*.csv"))]
    if not frames:
        raise SystemExit("no evaluation episode files found")
    return pd.concat(frames, ignore_index=True)


def main() -> None:
    df = load_all()
    rows = []
    for label, d in df.groupby("policy", sort=False):
        base = {"label": label, "group": group_of(label), "algorithm": d["algorithm"].iloc[0],
                "train_seed": d["train_seed"].iloc[0]}
        rows.append({**base, "category": "all", **summarise(d)})
        for cat, dc in d.groupby("category"):
            rows.append({**base, "category": cat, **summarise(dc)})
    by_label = pd.DataFrame(rows)
    by_label.to_csv(EVAL / "summary_by_label.csv", index=False)

    grp_rows = []
    for (group, cat), d in by_label.groupby(["group", "category"], sort=False):
        grp_rows.append({
            "group": group, "category": cat, "n_seeds": len(d),
            "episodes_per_seed": int(d["episodes"].iloc[0]),
            "success_mean": d["success_rate"].mean(), "success_std": d["success_rate"].std(ddof=0),
            "success_min": d["success_rate"].min(), "success_max": d["success_rate"].max(),
            "collision_mean": d["collision_rate"].mean(),
            "collision_std": d["collision_rate"].std(ddof=0),
            "timeout_mean": d["timeout_rate"].mean(), "return_mean": d["mean_return"].mean(),
            "length_mean": d["mean_length"].mean(), "path_mean": d["mean_path_length"].mean(),
            "ttg_mean": d["mean_time_to_goal_success"].mean(),
            "final_dist_mean": d["mean_final_distance"].mean(),
            "spl_approx_mean": d["spl_approx"].mean(),
        })
    by_group = pd.DataFrame(grp_rows)
    by_group.to_csv(EVAL / "summary_by_group.csv", index=False)

    cols = ["label", "category", "episodes", "success_rate", "collision_rate", "timeout_rate",
            "mean_return", "mean_length", "mean_path_length", "mean_time_to_goal_success",
            "mean_final_distance", "spl_approx"]
    md = ["# Evaluation summary (held-out test scenarios)\n",
          "Generated by scripts/summarize.py from results/evaluation/episodes/*.csv\n",
          "## Per evaluated policy\n", by_label[cols].round(3).to_markdown(index=False), "\n",
          "## Multi-seed groups (statistics over training seeds)\n",
          by_group.round(3).to_markdown(index=False), "\n"]
    (EVAL / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print(by_group[by_group.category == "all"].round(3).to_string(index=False))


def fmt(m, s=None, n=1):
    if pd.isna(m):
        return "--"
    if s is None or n <= 1:
        return f"{m:.2f}"
    return f"{m:.2f} $\\pm$ {s:.2f}"


def write_latex(g: pd.DataFrame) -> None:
    names = {"random": "Random", "heuristic": "Goal-seeking heuristic",
             "ppo_controlled_final": "PPO, 50k (1 seed)", "sac_controlled_final": "SAC, 50k (1 seed)",
             "ppo_extended_final": "PPO, 200k (3 seeds)", "sac_extended_final": "SAC, 200k (3 seeds)",
             "ppo_extended_best": "PPO, 200k best-val (3 seeds)",
             "sac_extended_best": "SAC, 200k best-val (3 seeds)"}
    order = [k for k in names if k in set(g.group)]
    lines = [r"\begin{tabular}{lcccccc}", r"\toprule",
             r"Policy & SR $\uparrow$ & CR $\downarrow$ & TR & Return & Path [m] & SPL$_\approx$ \\",
             r"\midrule"]
    for k in order:
        r = g[(g.group == k) & (g.category == "all")].iloc[0]
        n = int(r.n_seeds)
        lines.append(" & ".join([names[k], fmt(r.success_mean, r.success_std, n),
                                 fmt(r.collision_mean, r.collision_std, n), fmt(r.timeout_mean),
                                 f"{r.return_mean:.1f}", f"{r.path_mean:.2f}",
                                 fmt(r.spl_approx_mean)]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (TABLES / "overall.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [r"\begin{tabular}{lccc|ccc}", r"\toprule",
             r" & \multicolumn{3}{c|}{Success rate} & \multicolumn{3}{c}{Collision rate} \\",
             r"Policy & open & indoor & narrow & open & indoor & narrow \\", r"\midrule"]
    for k in order:
        cells = []
        for metric in ("success", "collision"):
            for cat in ("open", "indoor", "narrow"):
                r = g[(g.group == k) & (g.category == cat)].iloc[0]
                cells.append(fmt(r[f"{metric}_mean"], r[f"{metric}_std"], int(r.n_seeds)))
        lines.append(" & ".join([names[k]] + cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (TABLES / "by_category.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
